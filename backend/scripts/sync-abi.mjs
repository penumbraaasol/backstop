// Copies the compiled Backstop ABI from Foundry output into a typed TS module.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/Backstop.sol/Backstop.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const targets = [resolve(here, "../src/abi.ts"), resolve(here, "../../web/src/lib/abi.ts")];
const body = `// Generated by backend/scripts/sync-abi.mjs from contracts/out. Do not edit.\nexport const backstopAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
for (const t of targets) {
  try {
    mkdirSync(dirname(t), { recursive: true });
    writeFileSync(t, body);
    console.log("wrote", t);
  } catch (e) {
    console.warn("skip", t, e.message);
  }
}
